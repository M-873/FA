import io
import os
from PIL import Image, ImageDraw, ImageFont
from google import genai
from google.genai import types

from app.utils.config import get_settings
from app.utils.logging import logger
from app.utils.retry import with_retry


class GeminiImageGenerator:
    """Daily image generator powered by Google Gemini / Imagen models."""

    def __init__(self, api_key: str = None, image_model: str = None):
        settings = get_settings()
        self.api_key = api_key or settings.GEMINI_API_KEY
        self.image_model = image_model or settings.GEMINI_IMAGE_MODEL
        self.aspect_ratio = settings.IMAGE_ASPECT_RATIO
        self._client = None

    @property
    def client(self) -> genai.Client:
        if self._client is None:
            if not self.api_key:
                raise ValueError("GEMINI_API_KEY is required for image generation.")
            self._client = genai.Client(api_key=self.api_key)
        return self._client

    @with_retry(max_retries=3)
    def generate_image(self, prompt: str, output_path: str) -> str:
        """
        Generates image from text prompt using configured Gemini / Imagen model and saves to output_path.
        """
        logger.info(f"Generating image using model '{self.image_model}' with aspect ratio '{self.aspect_ratio}'...")

        if not self.api_key:
            logger.warning("No GEMINI_API_KEY provided. Creating fallback demonstration image for testing.")
            return self._create_placeholder_image(prompt, output_path)

        try:
            if "imagen" in self.image_model.lower():
                # Imagen model API call
                response = self.client.models.generate_images(
                    model=self.image_model,
                    prompt=prompt,
                    config=types.GenerateImagesConfig(
                        number_of_images=1,
                        aspect_ratio=self.aspect_ratio if self.aspect_ratio in ["1:1", "3:4", "4:3", "9:16", "16:9"] else "4:5",
                        output_mime_type="image/jpeg",
                    ),
                )
                if not response.generated_images:
                    raise RuntimeError("No image was generated by Imagen API.")

                image_bytes = response.generated_images[0].image.image_bytes
                image = Image.open(io.BytesIO(image_bytes))
                image.save(output_path, "JPEG", quality=95)
                logger.info(f"Successfully generated and saved image to {output_path}")
                return output_path

            else:
                # Multimodal Gemini image generation API call (e.g. gemini-2.5-flash-image)
                response = self.client.models.generate_content(
                    model=self.image_model,
                    contents=prompt,
                    config=types.GenerateContentConfig(
                        response_modalities=["IMAGE"],
                    ),
                )
                for part in response.candidates[0].content.parts:
                    if part.inline_data:
                        image = Image.open(io.BytesIO(part.inline_data.data))
                        image.save(output_path, "JPEG", quality=95)
                        logger.info(f"Successfully generated and saved Gemini image to {output_path}")
                        return output_path

                raise RuntimeError("No inline image data found in Gemini response.")

        except Exception as e:
            logger.error(f"Gemini image generation error: {e}")
            raise e

    def _create_placeholder_image(self, prompt: str, output_path: str) -> str:
        """Fallback placeholder image for dry-run/testing when API key is missing."""
        width, height = (1080, 1350) if self.aspect_ratio == "4:5" else (1080, 1080)
        img = Image.new("RGB", (width, height), color=(18, 24, 38))
        draw = ImageDraw.Draw(img)

        # Draw tech visual elements
        draw.rectangle([40, 40, width - 40, height - 40], outline=(0, 200, 255), width=4)
        title_text = "AI NEWS DAILY UPDATE"
        draw.text((80, 80), title_text, fill=(255, 255, 255))
        draw.text((80, 150), f"Prompt: {prompt[:80]}...", fill=(200, 220, 255))

        img.save(output_path, "JPEG")
        logger.info(f"Saved fallback demonstration image to {output_path}")
        return output_path
